class MockLLM:
    """
    Mock LLM that returns predefined demo responses.
    ALL outputs are clearly labeled as DEMO DATA.
    """

    def generate(self, prompt: str, scenario: Optional[str] = None) -> str:
        """
        Generate a mock response.

        Args:
            prompt:   User input (inspected for keywords)
            scenario: Override scenario (safe/hallucinated/partial/contradictory)
        """
        if scenario and scenario in DEMO_RESPONSES:
            base = DEMO_RESPONSES[scenario]
        elif any(w in prompt.lower() for w in ["tesla", "elon", "electric"]):
            base = DEMO_RESPONSES["safe"]
        elif any(w in prompt.lower() for w in ["einstein", "physics"]):
            base = DEMO_RESPONSES["contradictory"]
        elif any(w in prompt.lower() for w in ["eiffel", "paris", "tower"]):
            base = DEMO_RESPONSES["partial"]
        else:
            base = DEMO_RESPONSES["default"]

        # Always append demo label
        if "DEMO DATA" not in base:
            base += "\n\n⚠️ DEMO DATA – This is a mock response for demonstration purposes."

        return base


